"""Idempotent Scope Tree seed generator for the College Edition (IT3 Tenant #1 + additional Cohorts).

Usage:
    py scripts/seed_scope_tree.py
    py scripts/seed_scope_tree.py --major-code cs --major-name "علوم الحاسوب" --cohort-code cs3 --cohort-name "الدفعة الثالثة" --theory-prefix CS3_G --practical 3,3,3
"""
from __future__ import annotations

import argparse
import json
from typing import Sequence


def _sql_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def generate_seed_sql(
    *,
    college_code: str = "csit",
    college_name: str = "كلية علوم الحاسوب وتقنية المعلومات",
    major_code: str = "it",
    major_name: str = "تقنية المعلومات",
    cohort_code: str = "it3",
    cohort_name: str = "الدفعة الثالثة — المستوى الثالث",
    batch: str = "3",
    level: str = "المستوى الثالث",
    theory_prefix: str = "IT3_G",
    practical_per_theory: Sequence[int] = (3, 3, 3, 3),
) -> str:
    """Return an idempotent SQL block seeding College -> Major -> Cohort -> Theory/Practical Groups."""
    meta_json = json.dumps(
        {"batch": batch, "level": level, "theory_prefix": theory_prefix},
        ensure_ascii=False,
    )
    lines: list[str] = [
        "-- Idempotent Scope Tree seed (generated by scripts/seed_scope_tree.py)",
        "do $$",
        "declare",
        "  v_college bigint;",
        "  v_major   bigint;",
        "  v_cohort  bigint;",
        "  v_theory  bigint;",
        "begin",
        f"  select id into v_college from scope_nodes where kind = 'college' and parent_id is null and code = {_sql_str(college_code)} and deleted_at is null limit 1;",
        "  if v_college is null then",
        f"    insert into scope_nodes (kind, parent_id, code, name_ar, sort) values ('college', null, {_sql_str(college_code)}, {_sql_str(college_name)}, 1) returning id into v_college;",
        "  end if;",
        "",
        f"  select id into v_major from scope_nodes where kind = 'major' and parent_id = v_college and code = {_sql_str(major_code)} and deleted_at is null limit 1;",
        "  if v_major is null then",
        f"    insert into scope_nodes (kind, parent_id, code, name_ar, sort) values ('major', v_college, {_sql_str(major_code)}, {_sql_str(major_name)}, 1) returning id into v_major;",
        "  end if;",
        "",
        f"  select id into v_cohort from scope_nodes where kind = 'cohort' and parent_id = v_major and code = {_sql_str(cohort_code)} and deleted_at is null limit 1;",
        "  if v_cohort is null then",
        f"    insert into scope_nodes (kind, parent_id, code, name_ar, meta, sort) values ('cohort', v_major, {_sql_str(cohort_code)}, {_sql_str(cohort_name)}, {_sql_str(meta_json)}::jsonb, 1) returning id into v_cohort;",
        "  end if;",
        "",
    ]

    p_num = 0
    for t_idx, p_count in enumerate(practical_per_theory, start=1):
        t_code = f"{theory_prefix}{t_idx}"
        lines.extend([
            f"  select id into v_theory from scope_nodes where kind = 'theory_group' and parent_id = v_cohort and code = {_sql_str(t_code)} and deleted_at is null limit 1;",
            "  if v_theory is null then",
            f"    insert into scope_nodes (kind, parent_id, code, name_ar, sort) values ('theory_group', v_cohort, {_sql_str(t_code)}, {_sql_str(t_code)}, {t_idx}) returning id into v_theory;",
            "  end if;",
        ])
        for _ in range(p_count):
            p_num += 1
            p_code = f"G{p_num}"
            lines.extend([
                f"  if not exists (select 1 from scope_nodes where kind = 'practical_group' and parent_id = v_theory and code = {_sql_str(p_code)} and deleted_at is null) then",
                f"    insert into scope_nodes (kind, parent_id, code, name_ar, sort) values ('practical_group', v_theory, {_sql_str(p_code)}, {_sql_str(p_code)}, {p_num});",
                "  end if;",
            ])
        lines.append("")

    lines.append("end $$;")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate idempotent Scope Tree seed SQL")
    parser.add_argument("--college-code", default="csit")
    parser.add_argument("--college-name", default="كلية علوم الحاسوب وتقنية المعلومات")
    parser.add_argument("--major-code", default="it")
    parser.add_argument("--major-name", default="تقنية المعلومات")
    parser.add_argument("--cohort-code", default="it3")
    parser.add_argument("--cohort-name", default="الدفعة الثالثة — المستوى الثالث")
    parser.add_argument("--batch", default="3")
    parser.add_argument("--level", default="المستوى الثالث")
    parser.add_argument("--theory-prefix", default="IT3_G")
    parser.add_argument("--practical", default="2,2,2,2", help="Comma-separated practical counts per theory group")
    args = parser.parse_args()

    counts = tuple(int(x.strip()) for x in args.practical.split(",") if x.strip())
    sql = generate_seed_sql(
        college_code=args.college_code,
        college_name=args.college_name,
        major_code=args.major_code,
        major_name=args.major_name,
        cohort_code=args.cohort_code,
        cohort_name=args.cohort_name,
        batch=args.batch,
        level=args.level,
        theory_prefix=args.theory_prefix,
        practical_per_theory=counts,
    )
    print(sql)


if __name__ == "__main__":
    main()
